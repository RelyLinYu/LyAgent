import path from 'node:path';
import { auditReadability } from './audit_readability.mjs';

export async function checkKnowledge(context, base, out) {
  const page = await context.newPage();
  try {
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.goto(base);
    await page.locator('button.new-chat').click();
    await page.getByRole('heading', { name: '新对话', exact: true }).waitFor();
    await page.getByRole('textbox', { name: '消息', exact: true }).waitFor();
    await page.waitForFunction(() => !document.querySelector('[aria-label="消息"]').disabled);
    await page.getByLabel('选择附件', { exact: true }).setInputFiles({ name: 'knowledge-rules.md', mimeType: 'text/markdown', buffer: Buffer.from('预算上限 100 元\n负责人 张三\n') });
    await page.getByRole('button', { name: '移除附件 knowledge-rules.md', exact: true }).waitFor();
    await page.getByRole('button', { name: '知识', exact: true }).click();
    const region = page.getByRole('region', { name: '知识集合', exact: true });
    await region.getByLabel('集合名称', { exact: true }).fill('browser-rules');
    await region.getByRole('button', { name: '加入附件 knowledge-rules.md', exact: true }).click();
    await region.getByRole('button', { name: '保存集合版本', exact: true }).click();
    await region.getByText('已保存集合版本 1', { exact: true }).waitFor();
    await region.getByRole('button', { name: '固定到当前会话', exact: true }).click();
    await region.getByText('已固定到当前会话', { exact: true }).waitFor();
    const select = region.getByLabel('会话来源快照', { exact: true });
    await select.selectOption({ index: 1 });
    await region.getByLabel('知识检索词', { exact: true }).fill('预算');
    await region.getByRole('button', { name: '检索来源', exact: true }).click();
    await region.locator('.knowledge-results button').first().click();
    await region.getByRole('region', { name: '来源原文', exact: true }).getByText('knowledge-rules.md · 版本 1', { exact: true }).waitFor();
    for (const width of [1440, 800]) {
      await page.setViewportSize({ width, height: 900 });
      if (width === 800 && await page.locator('.sidebar').isVisible()) await page.getByRole('button', { name: '关闭侧栏', exact: true }).click();
      if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error('Knowledge overflow');
      await page.screenshot({ path: path.join(out, `knowledge-${width}.png`), fullPage: true });
    }
    await region.getByLabel('知识检索词', { exact: true }).fill('不存在的来源词');
    await region.getByRole('button', { name: '检索来源', exact: true }).click();
    await region.getByText('无匹配来源', { exact: true }).waitFor();
    await page.getByRole('button', { name: '对话', exact: true }).click();
    await page.getByRole('checkbox', { name: '任务验收', exact: true }).check();
    await page.getByLabel('任务知识快照', { exact: true }).selectOption({ index: 1 });
    await page.getByLabel('验收目标', { exact: true }).fill('核对固定知识预算');
    await page.getByRole('textbox', { name: '消息', exact: true }).fill('从显式知识快照检索预算');
    const submitted = page.waitForRequest(request => request.method() === 'POST' && new URL(request.url()).pathname.endsWith('/messages'));
    await page.getByRole('button', { name: '发送', exact: true }).click();
    const request = await submitted;
    if (request.postDataJSON().task.knowledge_snapshots.length !== 1) throw Error('Knowledge selection missing from contract');
    await page.getByText('知识快照实际检索：预算上限 100 元', { exact: true }).waitFor();
    await page.getByRole('button', { name: '运行详情', exact: true }).click();
    await page.getByRole('heading', { name: '任务通过', exact: true }).waitFor();
    await page.getByRole('button', { name: '关闭详情', exact: true }).click();
    await page.getByRole('checkbox', { name: '任务验收', exact: true }).check();
    await page.getByLabel('任务知识快照', { exact: true }).selectOption({ index: 1 });
    await page.getByLabel('验收目标', { exact: true }).fill('生成带来源机械检查的产物');
    await page.getByLabel('必需产物路径', { exact: true }).fill('source-report.md');
    await page.getByRole('checkbox', { name: '要求来源机械检查通过', exact: true }).check();
    await page.getByRole('textbox', { name: '消息', exact: true }).fill('根据固定来源写报告并执行机械检查');
    await page.getByRole('button', { name: '发送', exact: true }).click();
    await page.getByRole('button', { name: '批准这次调用', exact: true }).click();
    await page.getByText('来源机械检查已完成，语义未检查。', { exact: true }).waitFor();
    await page.getByRole('button', { name: '运行详情', exact: true }).click();
    const record = page.getByRole('region', { name: '执行任务记录', exact: true }).filter({ hasText: '生成带来源机械检查的产物' });
    await record.getByRole('heading', { name: '任务通过', exact: true }).waitFor();
    await record.getByText('3 / 16', { exact: true }).waitFor();
    await record.getByText('4 / 8', { exact: true }).waitFor();
    await record.getByText('来源机械检查 · 检查通过', { exact: true }).click();
    await record.getByText('仅检查固定来源、引文位置和数字；语义、冲突与完整性未检查。', { exact: true }).waitFor();
    for (const width of [1440, 800]) {
      await page.setViewportSize({ width, height: 900 });
      await page.screenshot({ path: path.join(out, `source-check-${width}.png`), fullPage: true });
    }
    await page.getByRole('button', { name: '关闭详情', exact: true }).click();
    await page.getByRole('checkbox', { name: '任务验收', exact: true }).check();
    await page.getByLabel('验收目标', { exact: true }).fill('工作流固定知识投影');
    await page.getByLabel('执行流程', { exact: true }).selectOption('read-knowledge@1');
    await page.getByLabel('执行团队', { exact: true }).selectOption('knowledge-readers@1');
    await page.getByLabel('任务知识快照', { exact: true }).selectOption({ index: 1 });
    await page.getByRole('textbox', { name: '消息', exact: true }).fill('工作流检索固定来源预算');
    await page.getByRole('button', { name: '发送', exact: true }).click();
    await page.getByRole('heading', { name: '流程结果', exact: true }).waitFor();
    await page.getByRole('button', { name: '运行详情', exact: true }).click();
    const workflowRecord = page.getByRole('region', { name: '执行任务记录', exact: true }).filter({ hasText: '工作流固定知识投影' });
    await workflowRecord.getByRole('heading', { name: '任务通过', exact: true }).waitFor();
    await workflowRecord.locator('summary').filter({ hasText: '工作单' }).click();
    await workflowRecord.getByText('知识快照实际检索：预算上限 100 元', { exact: true }).waitFor();
    await page.screenshot({ path: path.join(out, 'workflow-knowledge-800.png'), fullPage: true });
    await page.getByRole('button', { name: '关闭详情', exact: true }).click();
    await page.getByRole('checkbox', { name: '任务验收', exact: true }).check();
    await page.getByLabel('验收目标', { exact: true }).fill('工作流产物来源检查');
    await page.getByLabel('执行流程', { exact: true }).selectOption('check-knowledge@1');
    await page.getByLabel('执行团队', { exact: true }).selectOption('knowledge-readers@1');
    await page.getByLabel('任务知识快照', { exact: true }).selectOption({ index: 1 });
    await page.getByLabel('必需产物路径', { exact: true }).fill('workflow-report.md');
    await page.getByRole('checkbox', { name: '要求来源机械检查通过', exact: true }).check();
    await page.getByRole('textbox', { name: '消息', exact: true }).fill('写入工作流报告并检查来源');
    await page.getByRole('button', { name: '发送', exact: true }).click();
    await page.getByRole('button', { name: '批准这次调用', exact: true }).click();
    await page.getByRole('button', { name: '运行详情', exact: true }).click();
    const checkedWorkflow = page.getByRole('region', { name: '执行任务记录', exact: true }).filter({ hasText: '工作流产物来源检查' });
    await checkedWorkflow.getByRole('heading', { name: '任务通过', exact: true }).waitFor();
    await checkedWorkflow.getByText('来源机械检查 · 检查通过', { exact: true }).click();
    await page.screenshot({ path: path.join(out, 'workflow-source-check-800.png'), fullPage: true });
    await auditReadability(page, out, 'workflow-source-repair');
    await page.getByRole('button', { name: '关闭详情', exact: true }).click();
    await page.getByRole('button', { name: '知识', exact: true }).click();
    await region.getByLabel('会话来源快照', { exact: true }).selectOption({ index: 1 });
    await region.getByRole('button', { name: '取消固定快照', exact: true }).click();
    await region.getByText('已取消固定，历史任务快照保留', { exact: true }).waitFor();
    await region.getByLabel('新集合名称', { exact: true }).fill('browser-rules-renamed');
    await region.getByRole('button', { name: '重命名集合', exact: true }).click();
    await region.getByText('已重命名，历史版本与快照保留', { exact: true }).waitFor();
    await region.getByRole('button', { name: '新建集合', exact: true }).click();
    await region.getByLabel('导入知识来源', { exact: true }).setInputFiles({ name: 'standalone.md', mimeType: 'text/markdown', buffer: Buffer.from('Standalone source import') });
    await region.getByLabel('集合名称', { exact: true }).fill('standalone-browser');
    await region.getByRole('button', { name: '保存集合版本', exact: true }).click();
    await region.getByText('已保存集合版本 1', { exact: true }).waitFor();
  } finally { await page.close(); }
}
